"""Build IconColors.lua (Interface module): each spell icon's main colour, for
the cast line (PlayerCast.lua) to draw a cast in its icon's colour.

The icons are every spell's in Forever's own build (SpellMisc's
SpellIconFileDataID, from wago.tools, as make_library.py finds the build),
downloaded once from wago.tools' CASC files (BLP) into a cache, read with
Pillow. An icon's colour: its border cropped, each pixel weighted by how
vivid it is (saturation times brightness), the hue the weight piles up on
most (and its neighbours) averaged, then lifted to a bright, clear shade so
it reads on a thin line. An icon with little colour (steel, bone, white)
gets its average brightness as a grey.

    icons[fileDataID] = 0xRRGGBB

Usage:
    python tools/make_icon_colors.py [build]
"""
import colorsys
import io
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_library as ml  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ImprovedForever_Interface" / "IconColors.lua"
CACHE = ROOT / "tools" / "__pycache__" / "icons"
CASC = "https://wago.tools/api/casc/{}?download"

BINS = 36                   # (hue bins)
CROP = 0.1                  # (each side's border cropped)
GREY_BELOW = 0.05           # (vivid weight share under this: a grey icon)


def download(file_id):
    path = CACHE / f"{file_id}.blp"
    if path.exists() and path.stat().st_size > 0:
        return path
    req = urllib.request.Request(CASC.format(file_id), headers={"User-Agent": "ImprovedForever-tools"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            data = r.read()
    except Exception as e:  # noqa: BLE001
        print(f"  {file_id}: {e}")
        return None
    path.write_bytes(data)
    return path


def main_color(path):
    try:
        im = Image.open(io.BytesIO(path.read_bytes())).convert("RGB")
    except Exception as e:  # noqa: BLE001
        print(f"  {path.name}: {e}")
        return None
    w, h = im.size
    im = im.crop((int(w * CROP), int(h * CROP), int(w * (1 - CROP)), int(h * (1 - CROP)))).resize((32, 32))
    bins = [[0.0, 0.0, 0.0, 0.0] for _ in range(BINS)]      # (weight, r, g, b)
    total, bright = 0.0, 0.0
    for r, g, b in im.getdata():
        rf, gf, bf = r / 255, g / 255, b / 255
        hh, s, v = colorsys.rgb_to_hsv(rf, gf, bf)
        weight = s * v
        total += 1
        bright += v
        k = int(hh * BINS) % BINS
        bins[k][0] += weight
        bins[k][1] += rf * weight
        bins[k][2] += gf * weight
        bins[k][3] += bf * weight
    vivid = sum(x[0] for x in bins)
    if vivid / total < GREY_BELOW:
        v = max(0.6, min(0.95, bright / total + 0.25))
        return v, v, v
    best = max(range(BINS), key=lambda k: bins[k][0] + 0.5 * (bins[k - 1][0] + bins[(k + 1) % BINS][0]))
    acc = [0.0, 0.0, 0.0, 0.0]
    for k in (best - 1, best, (best + 1) % BINS):
        for i in range(4):
            acc[i] += bins[k][i]
    r, g, b = acc[1] / acc[0], acc[2] / acc[0], acc[3] / acc[0]
    hh, s, v = colorsys.rgb_to_hsv(r, g, b)
    # (bright and clear, for a thin line)
    return colorsys.hsv_to_rgb(hh, max(0.55, min(0.9, s * 1.2)), max(0.85, v))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else ml.forever_build()
    print(f"build {build}")
    CACHE.mkdir(parents=True, exist_ok=True)
    ids = sorted({int(r["SpellIconFileDataID"]) for r in ml.table("SpellMisc", build)
                  if r["SpellIconFileDataID"] not in ("", "0")})
    print(f"{len(ids)} icons")
    with ThreadPoolExecutor(max_workers=6) as pool:
        paths = list(pool.map(download, ids))
    colors = {}
    for file_id, path in zip(ids, paths):
        c = path and main_color(path)
        if c:
            colors[file_id] = (round(c[0] * 255) << 16) | (round(c[1] * 255) << 8) | round(c[2] * 255)
    lines = [
        "-- Generated by tools/make_icon_colors.py: each spell icon's main colour",
        "-- (SpellMisc's icons in Forever's build, from wago.tools), for the cast",
        "-- line (PlayerCast.lua). Don't edit by hand: run the tool again.",
        "local IF = ImprovedForever",
        "local IN = IF.Interface",
        "",
        f"IN.IconColors = {{ build = \"{build}\", icons = {{",
    ]
    for file_id in sorted(colors):
        lines.append(f"    [{file_id}] = 0x{colors[file_id]:06X},")
    lines.append("} }")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(colors)} colours -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
